export const ARCHETYPES: Record<ArchetypeId, Archetype> = {
  A,
  B,
  C,
  D,
  E,
  demo: DEMO,
};

export const ARCHETYPE_ORDER: ArchetypeId[] = ["A", "B", "C", "D", "E", "demo"];

export function getArchetype(id: string): Archetype {
  const a = ARCHETYPES[id as ArchetypeId];
  if (!a) {
    throw new Error(
      `unknown archetype '${id}' (expected one of ${ARCHETYPE_ORDER.join(", ")})`
    );
  }
  return a;
}

