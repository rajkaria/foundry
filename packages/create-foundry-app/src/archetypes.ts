/* ─────────────────── D — Consumer / RWA / tools ─────────────────────── */

const D: Archetype = {
  id: "D",
  title: "Consumer / RWA / tools",
  lead: "Drop in a co-owned model instantly — an HTTP endpoint, no web3 code needed to start.",
  needsKey: false,
  envLines: () => ["", "# Port for the local HTTP adapter.", "PORT=8787"],
  readmeBlurb:
    "Exposes a co-owned Ingot behind a plain HTTP endpoint (`POST /infer`) — your consumer app calls it like any API. Zero web3 code on the caller side; contribute domain data later to earn from the intelligence layer.",
  index: (
    ctx
  ) => `${header("Archetype D — co-owned model behind a plain HTTP endpoint")}
import { createServer } from "node:http";
import { Foundry, type IngotId } from "@foundryprotocol/sdk";

const network = ${networkExpr};
const rpcUrl = process.env.RPC_URL ?? "${RPC_FOR(ctx.network)}";
const ingotId = (process.env.INGOT_ID ?? "${DEMO_INGOT}") as IngotId;
const port = Number(process.env.PORT ?? "8787");

const foundry = new Foundry({ contracts: network, rpcUrl });

const server = createServer(async (req, res) => {
  if (req.method !== "POST" || req.url !== "/infer") {
    res.writeHead(404).end("POST /infer { input }");
    return;
  }
  let body = "";
  for await (const chunk of req) body += chunk;
  try {
    const { input } = JSON.parse(body || "{}");
    const { output, receipt } = await foundry.inference.run(ingotId, {
      input: String(input ?? "Hello"),
    });
    res.writeHead(200, { "content-type": "application/json" });
    res.end(JSON.stringify({ output, receipt }));
  } catch (err) {
    res.writeHead(500).end(String(err));
  }
});

server.listen(port, () => {
  console.log(\`co-owned model live → curl -XPOST localhost:\${port}/infer -d '{"input":"Hi"}'\`);
});
`,
};

