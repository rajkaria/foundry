/**
 * Archetype catalog for `create-foundry-app`.
 *
 * The five archetypes (A–E) mirror the builder segments in
 * `docs/0G-HACKATHON-INTEGRATION-PLAN.md` §2 — each leads with a different
 * value-prop and scaffolds a tailored, runnable `index.ts`. A sixth pseudo
 * archetype, `demo`, is the zero-setup one-command live-Ingot path: it targets
 * Galileo testnet, needs no key, and runs read-only inference against the
 * public demo Ingot.
 *
 * Archetype templates are the Foundry (ownership/revenue) path. The neutral
 * `@foundryprotocol/0gkit-*` quickstart lives behind `0g init` and the degit-able recipes in
 * `examples/` — see this package's README.
 */

/** The canonical public demo Ingot, used across the docs and the live demo. */
export const DEMO_INGOT = "ingot:0x8e2af4a000000000000000000000000000000001";

export type Network = "aristotle" | "galileo" | "local";

export type ArchetypeId = "A" | "B" | "C" | "D" | "E" | "demo";

export interface ArchetypeContext {
  /** Project directory name. */
  name: string;
  network: Network;
}

export interface Archetype {
  id: ArchetypeId;
  /** Short label shown in the CLI picker. */
  title: string;
  /** One-line lead value-prop (the §2 hook). */
  lead: string;
  /** Whether the generated project signs transactions (needs PRIVATE_KEY). */
  needsKey: boolean;
  /** Extra dependencies beyond the always-on base. */
  extraDeps?: Record<string, string>;
  /** Extra `.env.example` lines appended after the base block. */
  envLines: (ctx: ArchetypeContext) => string[];
  /** The README "What this template does" paragraph. */
  readmeBlurb: string;
  /** The generated, runnable `index.ts`. */
  index: (ctx: ArchetypeContext) => string;
}

const RPC_FOR = (n: Network): string =>
  n === "aristotle"
    ? "https://evmrpc.0g.ai"
    : n === "galileo"
      ? "https://evmrpc-testnet.0g.ai"
      : "http://127.0.0.1:8545";

/** Shared header every generated entrypoint opens with. */
const header = (title: string): string =>
  `// ${title}
// Generated by create-foundry-app. Docs: https://foundryprotocol.xyz/docs
import "dotenv/config";`;

const networkExpr =
  '(process.env.FOUNDRY_NETWORK as "aristotle" | "galileo" | "local") ?? "galileo"';

